def block_func(block_id: int, parameter: str, x: int, y: int) -> str:
    return f"""//[FuncIns],
//[名称] @{block_id},
//[禁用] False,
//[参数] {parameter},
//[坐标] X = {x},
//[坐标] Y = {y},
//[角度] 0,
//[/FuncIns],
"""


def block_loop(block_id: int, parameter: str, x: int, y: int) -> str:
    return f"""//[LoopIns],
//[名称] @{block_id},
//[禁用] False,
//[参数] {parameter},
//[坐标] X = {x},
//[坐标] Y = {y},
//[角度] 0,
//[/LoopIns],
"""


def block_cond_end(block_id: int, x: int, y: int) -> str:
    return f"""//[CondiEndIns],
//[名称] @{block_id},
//[禁用] False,
//[坐标] X = {x},
//[坐标] Y = {y},
//[角度] 0,
//[/CondiEndIns],
"""


def visual_user_functions() -> tuple[str, str]:
    blocks: list[str] = []
    links: list[str] = []
    next_id = 80

    for func_id, end_id, name, x, y, steps in VISUAL_USER_FUNCTION_SPECS:
        child_ids: list[int] = []
        blocks.append(f"""//[UserFunctionIns],
//[名称] @{func_id},
//[禁用] False,
//[参数] ?void {name},
//[坐标] X = {x},
//[坐标] Y = {y},
//[角度] 0,
//[展开] True,
//[/UserFunctionIns],
""")

        cursor_y = y + 56
        previous_id = func_id
        for step in steps:
            if len(step) == 3 and step[0] == "loop":
                loop_id = next_id
                next_id += 1
                loop_end_id = next_id
                next_id += 1
                child_ids.append(loop_id)
                blocks.append(block_loop(loop_id, step[1], x + 25, cursor_y))
                links.append(f"//[指令链接] @{previous_id} NextIns -> @{loop_id},")
                links.append(f"//[指令链接] @{loop_id} PreIns -> @{previous_id},")

                inner_previous = loop_id
                inner_y = cursor_y + 36
                for parameter in step[2]:
                    inner_id = next_id
                    next_id += 1
                    blocks.append(block_func(inner_id, parameter, x + 50, inner_y))
                    links.append(f"//[指令链接] @{inner_previous} NextIns -> @{inner_id},")
                    links.append(f"//[指令链接] @{inner_id} PreIns -> @{inner_previous},")
                    inner_previous = inner_id
                    inner_y += 30

                blocks.append(block_cond_end(loop_end_id, x + 25, inner_y))
                links.append(f"//[Loop结构链接] @{loop_id} CondiEnd -> @{loop_end_id},")
                links.append(f"//[指令链接] @{inner_previous} NextIns -> @{loop_end_id},")
                links.append(f"//[指令链接] @{loop_end_id} PreIns -> @{inner_previous},")
                previous_id = loop_end_id
                cursor_y = inner_y + 38
            else:
                child_id = next_id
                next_id += 1
                child_ids.append(child_id)
                blocks.append(block_func(child_id, step[0], x + 50, cursor_y))
                links.append(f"//[指令链接] @{previous_id} NextIns -> @{child_id},")
                links.append(f"//[指令链接] @{child_id} PreIns -> @{previous_id},")
                previous_id = child_id
                cursor_y += 30

        blocks.append(block_cond_end(end_id, x, cursor_y + 6))
        links.append(f"//[UserFunction结构链接] @{func_id} CondiEnd -> @{end_id},")
        links.append(f"//[指令链接] @{previous_id} NextIns -> @{end_id},")
        links.append(f"//[指令链接] @{end_id} PreIns -> @{previous_id},")

        if not child_ids:
            raise AssertionError(f"visual user function @{func_id} has no child blocks")

    return "".join(blocks), "\n".join(links) + "\n"


def enhance_visual_user_functions(text: str) -> str:
    block_start = text.find("//[UserFunctionIns],")
    block_end = text.find("//[变量],", block_start)
    link_start = text.find("//[指令链接] @39 NextIns")
    link_end = text.find("//[指令链接] @1 NextIns", link_start)
    if min(block_start, block_end, link_start, link_end) < 0:
        raise SystemExit("Could not locate visual user-function regions in generated LAB text")

    user_blocks, user_links = visual_user_functions()
    text = text[:block_start] + user_blocks + text[block_end:]
    link_start = text.find("//[指令链接] @39 NextIns")
    link_end = text.find("//[指令链接] @1 NextIns", link_start)
    if min(link_start, link_end) < 0:
        raise SystemExit("Could not locate visual user-function link region after block replacement")
    return text[:link_start] + user_links + text[link_end:]


def final_lab_text() -> str:
    text = enhance_visual_user_functions(LAB_TEXT)
    if "void main0()" not in text or "#param userspaceon" not in text:
        raise SystemExit("Generated LAB text lost executable code section")
    if text.count("//[UserFunctionIns]") != len(VISUAL_USER_FUNCTION_SPECS):
        raise SystemExit("Generated LAB text has unexpected user-function block count")
    if re.search(r"//\[指令链接\] @(\d+) NextIns -> @(\d+),\n//\[UserFunction结构链接\] @\1 CondiEnd -> @\2,", text):
        raise SystemExit("A visual user-function still links directly to its end block")
    return text


def ensure_modules() -> list[str]:
    missing: list[str] = []
    for module in MODULES:
        if not (LINKBOY_DIR / "Lib" / module).exists():
            missing.append(module)
    return missing


def read_gbk(path: Path) -> str:
    return path.read_text(encoding="gb18030", errors="replace")


def asset_report(lab_text: str) -> str:
    files = sorted(ASSET_DIR.glob("*.lab"), key=lambda p: p.name)
    if len(files) != 20:
        names = ", ".join(p.name for p in files) or "<empty>"
        raise SystemExit(f"Expected 20 asset .lab files under {ASSET_DIR}, got {len(files)}: {names}")

    feature_by_name = dict(ASSET_FEATURES)
    lines: list[str] = []
    lines.append("## 20 个分解素材吸收清单")
    lines.append("")
    lines.append("| 素材 | 组件数 | 事件块 | 函数块 | 循环块 | 连线数 | 吸收内容 |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: | --- |")
    for path in files:
        text = read_gbk(path)
        components = text.count("//[组件]")
        event_blocks = text.count("//[EventIns]")
        func_blocks = text.count("//[FuncIns]") + text.count("//[UserFunctionIns]")
        loop_blocks = text.count("//[LoopIns]") + text.count("//[ForeverIns]") + text.count("//[WhileIns]")
        link_count = text.count("//[链接]")
        feature = feature_by_name.get(path.name, "作为 LinkBoy 分解素材参与覆盖核对")
        lines.append(f"| `{path.name}` | {components} | {event_blocks} | {func_blocks} | {loop_blocks} | {link_count} | {feature} |")

    known = {name for name, _ in ASSET_FEATURES}
    missing_feature_notes = sorted(p.name for p in files if p.name not in known)
    if missing_feature_notes:
        raise SystemExit("Missing ASSET_FEATURES notes for: " + ", ".join(missing_feature_notes))

    lines.append("")
    lines.append("## 分解功能到总工程的映射")
    lines.append("")
    lines.append("| 总工程功能 | 来源素材 | 合并方式 |")
    lines.append("| --- | --- | --- |")
    for feature, sources, method in FINAL_FEATURE_MAP:
        lines.append(f"| {feature} | `{sources}` | {method} |")

    all_text = "\n".join(read_gbk(path) for path in files)
    asset_component_paths = sorted(set(re.findall(r"//\[组件路径\]\s*ModuleLib\s+(.*?),", all_text)))
    gui_text = lab_text
    required_terms = [
        "液晶屏", "信息显示器", "矩阵键盘", "无线接收器", "无线遥控器", "PPM遥控器",
        "湿度传感器", "称重传感器", "点阵屏", "灯带", "舵机", "四按钮", "延时器",
        "//[ForeverIns]", "//[IfElseIns]", "//[ElseIns]", "?void 可视化初始化系统",
    ]
    missing_terms = [term for term in required_terms if term not in gui_text]
    if missing_terms:
        raise SystemExit("Generated GUI is missing required visual terms: " + ", ".join(missing_terms))

    lines.append("")
    lines.append("## 素材静态核对")
    lines.append("")
    lines.append(f"- 分解素材数量：{len(files)} 个 `.lab`。")
    lines.append(f"- 分解素材累计组件块：{sum(read_gbk(path).count('//[组件]') for path in files)}。")
    lines.append(f"- 分解素材唯一组件路径：{len(asset_component_paths)} 类。")
    lines.append(f"- 总工程核心可视化组件：{lab_text.count('//[组件]')} 个。")
    lines.append(f"- 总工程事件块：{lab_text.count('//[EventIns]')} 个；用户自定义无值函数块：{lab_text.count('//[UserFunctionIns]')} 个。")
    lines.append(f"- 总工程条件/否则块：IfElse={lab_text.count('//[IfElseIns]')}，Else={lab_text.count('//[ElseIns]')}；反复执行块 Forever={lab_text.count('//[ForeverIns]')}，Loop={lab_text.count('//[LoopIns]')}。")
    lines.append(f"- 总工程硬件连线：{lab_text.count('//[链接]')} 条；指令结构连线：{lab_text.count('//[指令链接]')} 条。")
    lines.append("")
    return "\n".join(lines)


def write_gbk(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.strip().replace("\n", "\r\n").encode("gbk"))


def write_utf8(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.strip() + "\n", encoding="utf-8")


def backup_recent_list() -> Path | None:
    if not RECENT_LIST.exists():
        return None
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = RECENT_LIST.with_name(f"{RECENT_LIST.name}.{stamp}.bak")
    backup.write_bytes(RECENT_LIST.read_bytes())
    return backup


def update_recent_list() -> None:
    content = f"{OUTPUT_LAB}\r\n{OUTPUT_DESKTOP}\r\n<end>\r\n"
    RECENT_LIST.write_bytes(content.encode("gbk"))


def main() -> None:
    missing = ensure_modules()
    if missing:
        raise SystemExit("Missing LinkBoy modules:\n" + "\n".join(missing))

    lab_text = final_lab_text()
    write_gbk(OUTPUT_LAB, lab_text)
    write_gbk(OUTPUT_DESKTOP, lab_text)
    backup = backup_recent_list()
    update_recent_list()

    report = REPORT_TEXT + "\n\n" + asset_report(lab_text)
    if backup:
        report += f"\n\n## 最近文件备份\n\n- `{backup}`\n"
    report += f"\n\n## 生成时间\n\n- {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
    write_utf8(REPORT, report)

    print(f"lab={OUTPUT_LAB}")
    print(f"desktop={OUTPUT_DESKTOP}")
    print(f"report={REPORT}")
    if backup:
        print(f"recent_backup={backup}")


if __name__ == "__main__":
    main()
